#!/usr/bin/env python3
"""Regenerate theme.css from the installed DSH app (read-only).

Source of truth: @deepseek-ai/dsh-client-ui-theme/lib/client.js inside app.asar
(design-platform / base / gradient-shadow-text CSS strings). We only emit the
--dsw-* tokens lib/client.js references plus everything they transitively
reference, scoped exactly like the host: body (light), body[data-ds-dark-theme]
(dark), and `body, body *` (elevation tokens that must re-resolve per element).

Usage: python3 test/ui-harness/gen_theme.py [--asar PATH]
"""
import argparse, json, os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CLIENT = os.path.join(HERE, '..', '..', 'lib', 'client.js')
ASAR = '/Applications/DeepSeek Harness.app/Contents/Resources/app.asar'
THEME_FILE = '/dsh/node_modules/@deepseek-ai/dsh-client-ui-theme/lib/client.js'


def read_asar_file(asar, want):
    with open(asar, 'rb') as f:
        head = f.read(16)
        hdr_size = struct.unpack('<I', head[12:16])[0]
        hdr = json.loads(f.read(hdr_size).decode())
        base = 8 + struct.unpack('<I', head[4:8])[0]
        node = hdr
        for part in want.strip('/').split('/'):
            node = node['files'][part]
        f.seek(base + int(node['offset']))
        return f.read(node['size']).decode('utf8', 'replace')


def css_strings(js):
    out = {}
    for m in re.finditer(r'(?:var|const) ([A-Za-z_$0-9]+) = ("(?:[^"\\]|\\.)*")', js):
        try:
            out[m.group(1)] = json.loads(m.group(2))
        except Exception:
            pass
    return out


def decls(body):
    d = {}
    for part in body.split(';'):
        if ':' in part and part.strip().startswith('--'):
            k, v = part.split(':', 1)
            d[k.strip()] = v.strip()
    return d


def collect(css_map):
    """Return (light, dark_overrides, star) where star = tokens the host declares on `body *`
    (they must stay per-element so local overrides like --dsw-elevation-stroke-color work)."""
    light, dark, star = {}, {}, {}
    for name in ('base_css_default', 'design_platform_css_default', 'gradient_shadow_text_css_default'):
        css = css_map.get(name, '')
        for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', css):
            sel = m.group(1).strip().split('\n')[-1].strip()
            if sel in (':root', 'body'):
                light.update(decls(m.group(2)))
            elif sel == 'body,body *':
                star.update(decls(m.group(2)))
            elif sel == 'body[data-ds-dark-theme]':
                dark.update(decls(m.group(2)))
    return light, dark, star


def closure(names, tables):
    """Tokens plus every --dsw-* they transitively reference."""
    seen, todo = set(), list(names)
    while todo:
        t = todo.pop()
        if t in seen:
            continue
        seen.add(t)
        for tab in tables:
            if t in tab:
                todo += re.findall(r'var\((--[a-z0-9-]+)', tab[t])
    return seen


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--asar', default=ASAR)
    a = ap.parse_args()
    used = sorted(set(re.findall(r'var\((--dsw-[a-z0-9-]+)', open(CLIENT, encoding='utf8').read())))
    light, dark, star = collect(css_strings(read_asar_file(a.asar, THEME_FILE)))
    missing = [t for t in used if t not in light and t not in star]
    need = closure(used, [light, dark, star])
    def block(sel, table, keys):
        rows = ['  %s: %s;' % (t, table[t]) for t in sorted(keys) if t in table]
        return sel + ' {\n' + '\n'.join(rows) + '\n}\n'
    # Host scopes theme to body / body[data-ds-dark-theme]; harness does the same so
    # var() chains resolve exactly like in DSH (no pre-flattening).
    css = ('/* generated by gen_theme.py from ' + THEME_FILE + ' — do not hand-edit */\n'
           + '/* client.js tokens missing in host: ' + (', '.join(missing) or 'none') + ' */\n'
           + block('body', light, need)
           + block('body[data-ds-dark-theme]', dark, need)
           + block('body, body *', star, need))
    open(os.path.join(HERE, 'theme.css'), 'w', encoding='utf8').write(css)
    print('tokens used by client.js: %d, emitted: %d' % (len(used), len(used) - len(missing)))
    print('missing in host: ' + (', '.join(missing) or 'none'))


if __name__ == '__main__':
    sys.exit(main())
